#!/usr/bin/env python3
"""Export saved TaskRes/SS-Text+ numerical records; never run model inference."""

import csv
import hashlib
import io
import json
from pathlib import Path


PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent
SOURCE = ROOT / "experiments/fewshot_taskres_sstext_20261109/runs/full_20261109_v1"
METHODS = {"taskres", "sstext_plus"}
MODELS = {"AlphaRAD", "BiomedCLIP"}
DATASETS = {"rsna_pneumonia", "chestxdet10"}
# Export only the added methods and the Q-minus-adapter contrasts reported in
# the manuscript. Existing native branches remain in fewshot_development_*.
EXPORTS = (
    ("means.csv", "means", 8, ("model", "dataset", "method")),
    ("per_seed.csv", "seeds", 40, ("model", "dataset", "method", "seed")),
    ("comparisons.csv", "comparisons", 8, ("model", "dataset", "target", "reference")),
    ("per_class.csv", "per_class", 44, ("model", "dataset", "method", "class_name")),
)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def main():
    result_bytes = (SOURCE / "RESULTS.json").read_bytes()
    results = json.loads(result_bytes)
    if results["status"] != "complete" or results["seeds"] != list(range(42, 47)):
        raise ValueError("Unexpected result status or support draws")

    pending = []
    sources = {str((SOURCE / "RESULTS.json").relative_to(ROOT)): sha256(result_bytes)}
    for filename, suffix, expected_count, identity in EXPORTS:
        source = SOURCE / filename
        raw = source.read_bytes()
        digest = sha256(raw)
        if digest != results["output_sha256"][filename]:
            raise ValueError(f"Source hash mismatch: {filename}")
        sources[str(source.relative_to(ROOT))] = digest
        reader = csv.DictReader(io.StringIO(raw.decode("utf-8")))
        fields = [key for key in reader.fieldnames if not key.startswith("average_precision")]
        rows = []
        for row in reader:
            selected = (
                row["target"] == "query" and row["reference"] in METHODS
                if suffix == "comparisons" else row["method"] in METHODS
            )
            if selected:
                rows.append({key: row[key] for key in fields})
        if len(rows) != expected_count or len({tuple(r[k] for k in identity) for r in rows}) != expected_count:
            raise ValueError(f"Unexpected count or duplicate records: {filename}")
        if {r["model"] for r in rows} != MODELS or {r["dataset"] for r in rows} != DATASETS:
            raise ValueError(f"Unexpected model/dataset coverage: {filename}")
        if any("/storage/" in value or "/home/" in value for row in rows for value in row.values()):
            raise ValueError(f"Local path in export: {filename}")
        text = io.StringIO(newline="")
        writer = csv.DictWriter(text, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)  # Retain the source decimal strings without rounding.
        name = f"fewshot_taskres_sstext_{suffix}.csv"
        pending.append((name, text.getvalue().encode("utf-8"), len(rows)))

    # Validate every input before replacing any export. No other CSV or table
    # is regenerated by this script.
    destination = PAPER / "supplement_data"
    destination.mkdir(parents=True, exist_ok=True)
    outputs = {}
    for name, data, count in pending:
        path = destination / name
        temporary = path.with_suffix(".csv.tmp")
        temporary.write_bytes(data)
        temporary.replace(path)
        outputs[name] = {"rows": count, "sha256": sha256(data)}
    audit = {
        "scope": "TaskRes/SS-Text+ means, support draws, class summaries, and reported Q-minus-adapter contrasts",
        "no_model_inference": True,
        "no_metric_recomputation": True,
        "decimal_strings_preserved": True,
        "metrics": ["auroc", "trapezoidal_auprc"],
        "seeds": results["seeds"],
        "bootstrap_replicates": results["bootstrap_replicates"],
        "bootstrap_seed": results["bootstrap_seed"],
        "sources_sha256": sources,
        "outputs": outputs,
    }
    build = PAPER / "build"
    build.mkdir(parents=True, exist_ok=True)
    (build / "TASKRES_SSTEXT_CSV_EXPORT_AUDIT.json").write_text(json.dumps(audit, indent=2) + "\n")
    print(json.dumps({name: info["rows"] for name, info in outputs.items()}, indent=2))


if __name__ == "__main__":
    main()
